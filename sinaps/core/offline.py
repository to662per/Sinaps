"""Жёсткий запрет сетевых вызовов в ядре.

Зачем этот модуль
-----------------
В `PrivacyConfig` был флаг `local_only` с комментарием «жёсткий запрет
сетевых вызовов (требование проекта)». Проверка кода показала, что флаг
читался в двух местах — и оба раза только для **печати текста**:
«локально, без сети» либо «СЕТЬ РАЗРЕШЕНА». Ничто не блокировалось.
Поставь `local_only: false` — изменится надпись, а не поведение.

То есть обещание приватности было записано, но не выполнялось. Это
именно тот случай, когда документация опаснее её отсутствия: читатель
верит и перестаёт проверять.

Два скрытых канала были найдены измерением, а не чтением:

  1. `faster-whisper`. Конструктору передаётся `download_root`, но не
     `local_files_only`. Если модель удалена, библиотека молча идёт на
     HuggingFace. Параметр в библиотеке есть (`transcribe.py:630`).
  2. `silero` TTS. `torch.hub.load(..., source="github")` — явная
     загрузка с GitHub при пустом кэше.

    Пока модели скачаны установщиком, оба канала молчат. Стоит удалить
    модель — и ядро выходит в интернет, обещав этого не делать.

Что здесь
---------
Запрет сделан **структурой кода**, а не переключателем:

  * переменные окружения выставляются до того, как импортирован хоть
    какой-нибудь сетевой пакет — иначе `huggingface_hub` успевает их
    прочитать при импорте;
  * загрузчикам моделей передаётся запрет скачивания;
  * отсутствие модели даёт понятную ошибку с указанием запустить
    установщик, а не молча тянет сеть.

Флага нет намеренно. Если сделать `offline: false`, приватность снова
станет опцией, а «железобетонный запрет» — настройкой, которую можно
случайно включить обратно.

Что остаётся на пограничных случаях
-----------------------------------
`sinaps/setup.py` ходит в сеть — он качает модели при установке. Это
отдельная программа, которую человек запускает руками. Во время работы
ассистента она не участвует, и проверка на сетевые импорты её не видит
намеренно: установщик сеть использовать обязан.

Плагины. Плагин с разрешением `network.http` получает доступ через
прокси `sinaps/plugins/network.py`. Ядро этот модуль не импортирует
никогда — даже при выданном разрешении.
"""

from __future__ import annotations

import logging
import os
from pathlib import Path

from .errors import SinapsError

log = logging.getLogger("sinaps.offline")

#: Проектные каталоги. Модели лежат рядом с кодом, а не в пользовательских
#: настройках: так установщик и ассистент смотрят в одно место.
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent

#: Переменные, которые библиотеки читают при первом импорте.
#:
#: `HF_HUB_OFFLINE` — запрет для huggingface_hub (faster-whisper тянет
#: веса оттуда). `TRANSFORMERS_OFFLINE` — на случай, если появится
#: transformers. Ставим именно `1`: библиотеки проверяют наличие
#: переменной, а не значение.
_OFFLINE_VARS = (
    "HF_HUB_OFFLINE",
    "TRANSFORMERS_OFFLINE",
    "HF_DATASETS_OFFLINE",
)


class MissingModelError(SinapsError):
    """Модели нет на диске, а скачивать запрещено.

    Отдельный тип, чтобы отличать «нет модели» от прочих поломок и
    говорить человеку точное объяснение, а не «движок недоступен».

    Наследует `SinapsError` — не `RuntimeError`, и это важно. Обработчик
    диалога ловит `SinapsError` и произносит `exc.speech` вслух
    (`conversation/pipeline.py:183`). Обычное исключение уходит в
    `except Exception`, и человек вместо «Запусти setup_sinaps.bat»
    услышит «Что-то пошло не так, попробуй ещё раз» — то есть
    приложение не сможет объяснить, что ему мешает работать.
    """


def enforce_offline() -> None:
    """Запретить библиотекам выход в сеть.

    Вызывать **до** импорта `faster_whisper`, `torch` и прочих: они
    читают переменные окружения в момент импорта, и поставленные позже
    значения уже не подействуют.
    """
    for name in _OFFLINE_VARS:
        os.environ.setdefault(name, "1")

    # torch.hub смотрит сюда и тоже уважает режим офлайн при
    # `torch.hub.set_dir`, но молчаливого переключателя у него нет —
    # за это отвечает проверка кэша в `require_tts_models`.
    log.debug("Оффлайн-режим включён: %s", ", ".join(_OFFLINE_VARS))


def hub_dir() -> Path:
    """Каталог кэша torch.hub — там лежат модели silero."""
    return Path(os.environ.get("TORCH_HOME", Path.home() / ".cache" / "torch")
                ) / "hub"


def hub_repo_path() -> Path:
    """Папка с кодом моделей silero в кэше torch.hub.

    Именно её отдаём `torch.hub.load(source="local")`. При `source=
    "github"` библиотека при пустом кэше выходит в интернет сама;
    при `"local"` читает `hubconf.py` с диска и сеть не задействует
    вовсе. Установщик складывает папку заранее.
    """
    return hub_dir() / "snakers4_silero-models_master"


def require_tts_models() -> None:
    """Проверить, что модель синтеза лежит в кэше torch.hub.

    `torch.hub.load(..., source="github")` при пустом кэше идёт в сеть.
    Раз сеть запрещена, отсутствие кэша — это понятная ошибка, а не
    повод скачать.
    """
    expected = hub_repo_path()
    if not (expected / "hubconf.py").exists():
        raise MissingModelError(
            "Модель синтеза не найдена в кэше torch.hub. Сеть в ядре "
            f"запрещена, скачивать нельзя.\nОжидалось: {expected / 'hubconf.py'}\n"
            "Запусти setup_sinaps.bat — он скачает модели при установке."
        )


def require_whisper_model(model_name: str,
                          download_root: str | os.PathLike[str]) -> None:
    """Проверить, что веса faster-whisper лежат на диске.

    То же рассуждение, что в `require_tts_models`: без проверки
    библиотека просто уходит в интернет.

    Признак модели — файл `model.bin` внутри её папки, а не само
    название папки. Первая версия проверки искала `--<имя модели>` в
    имени каталога, и это было неверно: huggingface_hub называет папку
    `models--<владелец>--faster-whisper-<модель>`, так что перед именем
    модели стоит одиночный дефис, а не два. Проверка объявляла
    отсутствующей модель, которая лежала на диске, и ассистент отказался
    бы работать с установленной моделью.
    """
    root = Path(download_root)
    if not root.exists():
        raise MissingModelError(
            f"Каталог моделей не найден: {root}\n"
            "Запусти setup_sinaps.bat — он скачает модели при установке."
        )

    for candidate in sorted(root.glob("models--*")):
        if model_name not in candidate.name:
            continue
        # Пустая папка кэша — это не модель. Ищем именно веса.
        if any(candidate.rglob("model.bin")):
            return

    found = sorted(p.name for p in root.glob("models--*"))
    raise MissingModelError(
        f"Модель распознавания «{model_name}» не найдена в {root}. "
        "Сеть в ядре запрещена, скачивать нельзя.\n"
        + (f"На диске есть: {', '.join(found)}\n" if found else "")
        + "Запусти setup_sinaps.bat — он скачает модели при установке."
    )


def describe() -> str:
    """Человеческое описание режима — для вывода при запуске."""
    return "локально, без сети (модели уже на диске)"


#: Сетевые пакеты, которые при их импорте тянут за собой возможность
#: выйти в сеть. Их отсутствие в процессе — измеримый признак того, что
#: оффлайн-режим держится, а не просто объявлен.
_NETWORK_PACKAGES = ("httpx", "requests", "aiohttp", "urllib3")


def report() -> str:
    """Что можно сказать про сеть — по фактам, а не по флагу.

    Раньше эту строку печатали по `privacy.local_only`, и флаг при этом
    ничего не делал: он читался только для печати. На экране
    появлялось «локально, без сети», и человек переставал искать, чем
    оно подкреплено. Хуже, чем не печатать ничего: обещание без
    проверки вреднее отсутствия обещания.

    Здесь три измеримых признака: флаги оффлайна выставлены, в пакете
    нет сетевых импортов (это проверяет `test_architecture.py`), и в
    процессе нет загруженных сетевых модулей.
    """
    import sys

    missing = [name for name in _OFFLINE_VARS if not os.environ.get(name)]
    if missing:
        return (f"ПРЕДУПРЕЖДЕНИЕ: оффлайн-режим не включён, "
                f"не выставлены: {', '.join(missing)}")

    loaded = sorted(name for name in _NETWORK_PACKAGES if name in sys.modules)
    if loaded:
        return (f"ВНИМАНИЕ: в процессе загружены сетевые модули: "
                f"{', '.join(loaded)}")

    return describe()
