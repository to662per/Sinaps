#: Формы, которые встречаются в разных навыках и идут первыми.
#: Регулярка требует длинных вариантов раньше коротких, иначе
#: «открыть» перехватит начало «открывайте».
def _ordered(words: tuple[str, ...]) -> tuple[str, ...]:
    return tuple(sorted({w for w in words if w}, key=lambda w: (-len(w), w)))


_ORDERED: dict[str, tuple[str, ...]] = {
    key: _ordered(value) for key, value in _FORMS.items()
}


def forms_of(lemma: str) -> tuple[str, ...]:
    """Все формы глагола по инфинитиву. Пусто, если глагол неизвестен."""
    return _ORDERED.get(lemma, ())


def alt(*words: str) -> str:
    """Чередование для регулярного выражения из произвольных слов."""
    return "(?:" + "|".join(_ordered(tuple(words))) + ")"


@lru_cache(maxsize=None)
def verb_pattern(lemmas: tuple[str, ...]) -> str:
    """Регулярка со всеми формами перечисленных глаголов.

    Неизвестные глаголы берутся как есть: молча пропавший глагол
    хуже лишней формы.
    """
    words: list[str] = []
    for lemma in lemmas:
        known = _ORDERED.get(lemma)
        words.extend(known if known else ([lemma] if lemma else []))
    return alt(*words)


def verb(*lemmas: str) -> str:
    """Короткая запись для навыков: `verb("открыть", "запустить")`."""
    return verb_pattern(tuple(lemmas))


def verb_with(extra: str, *lemmas: str) -> str:
    """Формы глаголов плюс заданные слова.

    Нужно там, где к глаголу относятся не все объекты: «сделай
    скриншот» — да, «сделаю шкаф» — нет.
    """
    words = [extra]
    for lemma in lemmas:
        known = _ORDERED.get(lemma)
        words.extend(known if known else ([lemma] if lemma else []))
    return alt(*words)