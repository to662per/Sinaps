"""Нормализация распознанного текста.

Распознавание речи даёт текст, который почти правильный: «ё» вместо «е»,
лишние пробелы, «пятнадцать» вместо «15», иногда — опечатки. Здесь текст
приводится к виду, по которому уже можно искать команды.

Важно: это НЕ исправление смысла. Мы не додумываем слова — только приводим
к канонической форме, чтобы регулярные выражения работали предсказуемо.
"""

from __future__ import annotations

import re

#: Префиксы, которые Whisper/Sinaps добавляют из контекста и которые не
#: являются частью команды.
_PREFIXES = re.compile(
    r"^\s*(?:"
    r"синапс[,\s]+|"
    r"ok[,\s]+|"
    r"ладно[,\s]+|"
    r"слушай[,\s]+|"
    r"внимание[,\s]+|"
    r")",
    re.IGNORECASE,
)

#: Типичные ошибки распознавания русской речи -> правильное слово.
#: Собрано из реальных промахов Whisper на коротких командах.
_COMMON_ERRORS = {
    "блохнот": "блокнот",
    "блокхнот": "блокнот",
    "блокнот": "блокнот",
    "калькулятор": "калькулятор",
    "калькулятро": "калькулятор",
    "калкулятор": "калькулятор",
    "проводник": "проводник",
    "проводнмк": "проводник",
    "пряводник": "проводник",
    "динспетчер": "диспетчер",
    "задачь": "задач",
    "звдач": "задач",
    "громкость": "громкость",
    "громкост": "громкость",
    "выключи": "выключи",
    "виключи": "выключи",
    "включи": "включи",
    "вкллючи": "включи",
    "перезаряди": "перезагрузи",
    "перезаряжает": "перезагрузи",
    "таймер": "таймер",
    "таймр": "таймер",
    "заметк": "заметка",
    "заметки": "заметки",
    "скриншот": "скриншот",
    "риншот": "скриншот",
}

#: Падежи и лишние слова, которые мешают точному совпадению.
_PUNCTUATION = re.compile(r"[^\w\s:,.?!-]", re.UNICODE)
_MULTISPACE = re.compile(r"\s+")

#: Знаки конца предложения, которые Whisper ставит сам.
#:
#: Шаблоны команд привязаны `^...$`, поэтому «дата» совпадает, а «Дата.» —
#: нет: точка в конце не даёт сработать якорю. Раньше это лечили в
#: каждом шаблоне отдельно и непоследовательно: «Который час?» работал,
#: а «Какая сегодня дата?» — нет.
#:
#: Убираем ТОЛЬКО хвост. Внутри текста знаки остаются: они несут смысл
#: («10:30», «5,5 минут», «отчёт.txt»).
_TRAILING_PUNCT = re.compile(r"[.,!?;:…]+$")

#: Метка порядка байтов (UTF-8 BOM, U+FEFF) в начале текста.
#:
#: Её НЕ убирает `str.strip()`: в Python `'\ufeff'.isspace()` ложно, BOM —
#: не пробельный символ, а невидимый. При этом он приезжает сразу из
#: файлов, сохранённых в UTF-8 с BOM (их пишет в том числе «Блокнот»),
#: из конвейера PowerShell и из `utf-8-sig` CSV. Незаметен, но ломает:
#: имя файла становится несуществующим, а фраза не совпадает с командой.
_BOM = "﻿"


def strip_bom(text: str) -> str:
    """Убирает BOM в начале. Внутренние и хвостовые не трогает."""
    return (text or "").lstrip(_BOM)


def normalize(text: str, *, keep_yo: bool = False) -> str:
    """Приводит текст к каноническому виду для сопоставления с командами.

    `keep_yo=True` сохраняет букву «ё». Это критично для имён файлов:
    без этого «отчёт.txt» превращается в «отчет.txt», которого не
    существует, и навык не найдёт файл.
    """
    if not text:
        return ""

    text = strip_bom(text).strip().lower()
    text = _PREFIXES.sub("", text)
    if not keep_yo:
        text = text.replace("ё", "е")

    # Ошибки распознавания чиним только в словах, а не во всём тексте:
    # иначе «телеграм» превратится в мусор.
    for wrong, right in _COMMON_ERRORS.items():
        text = re.sub(rf"\b{re.escape(wrong)}\b", right, text)

    text = _PUNCTUATION.sub(" ", text)
    text = _MULTISPACE.sub(" ", text)
    text = text.strip()
    # Хвостовые знаки конца предложения — после стерилизации пробелов,
    # иначе «дата ?» не очистится.
    return _TRAILING_PUNCT.sub("", text)


def strip_quotes(text: str) -> str:
    """Убирает внешние кавычки: «блокнот» -> блокнот."""
    text = strip_bom(text).strip()
    for opening, closing in (('"', '"'), ("«", "»"), ("'", "'"), ("“", "”")):
        if len(text) >= 2 and text.startswith(opening) and text.endswith(closing):
            return text[1:-1].strip()
    return text


def cleanup(text: str, *, keep_yo: bool = False) -> str:
    """Финальная чистка значения слота перед использованием.

    `keep_yo=True` — для путей и имён собственных (см. `normalize`).
    """
    text = normalize(text, keep_yo=keep_yo)
    text = strip_quotes(text)
    text = _MULTISPACE.sub(" ", text)
    # Остатки служебных слов в начале значения слота.
    text = re.sub(r"^(?:на|за|до|по|в|во|через)\s+", "", text)
    return text.strip(" .,!?-")


def normalize_for_match(text: str) -> str:
    """Версия для нечёткого сравнения: без пробелов и знаков."""
    return re.sub(r"[\s\-_]", "", normalize(text))
