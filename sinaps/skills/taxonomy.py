"""Группы навыков: русские названия, значки, порядок.

Зачем отдельный модуль
----------------------
Название группы нужно трём местам: вкладкам панели возможностей,
речи ассистента и подсказкам. Если каждое придумает своё, через неделю
панель скажет «Окна», а ассистент вслух — «windows — 4», и человек
решит, что это два разных навыка.

Ключ группы — префикс намерения до точки: `media.volume_up` -> `media`.
Набор групп зашит сюда, а не собирается из реестра, потому что порядок
вкладок и человеческие названия задаёт человек, а не код. Количество
команд внутри группы реестр считает сам.

Группы, которых здесь нет, не показываются: новая группа в коде без
записи здесь не появится ни в панели, ни в речи. Это сделано намеренно —
лучше не показать, чем показать подпись «unknown».
"""

from __future__ import annotations

from dataclasses import dataclass

#: Префикс намерения -> описание группы.
#: Порядок в словаре задаёт порядок вкладок в панели.
TAXONOMY: dict[str, "Group"] = {}


@dataclass(frozen=True)
class Group:
    """Описание группы навыков для интерфейса и для речи."""

    key: str
    title: str                  # человеческое название: «Звук и музыка»
    icon: str                    # значок для карточки
    short: str = ""              # коротко для речи: «звук»
    #: Слова, которыми человек заводит речь об этой группе. Нужны,
    #: чтобы он мог сказать «покажи звук» и попасть на вкладку.
    voice: tuple[str, ...] = ()

    def __post_init__(self) -> None:
        if not self.short:
            object.__setattr__(self, "short", self.title.lower())
        TAXONOMY[self.key] = self


Group("windows", "Окна", "🪟", "окна", ("окна", "окно"))
Group("apps", "Программы и файлы", "📁", "программы",
      ("программы", "файлы", "приложения"))
Group("media", "Звук и музыка", "🎵", "звук",
      ("звук", "музыка", "медиа", "громкость"))
Group("time", "Время и дата", "⏰", "время", ("время", "дата"))
Group("system_info", "Состояние системы", "📊", "система", ("система",))
Group("screen", "Экран", "💡", "экран", ("экран", "скриншот"))
Group("clipboard", "Буфер обмена", "📋", "буфер", ("буфер", "копировать"))
Group("power", "Питание", "⚡", "питание", ("питание",))
Group("smalltalk", "Разговор", "💬", "разговор", ("разговор",))


def group_of(intent_name: str) -> str:
    """Ключ группы по полному имени намерения: `media.next` -> `media`."""
    return intent_name.split(".", 1)[0]


def describe(key: str) -> Group | None:
    """Описание группы или None, если её нет в таксономии."""
    return TAXONOMY.get(key)


def known_groups() -> list[str]:
    """Ключи групп в порядке вкладок."""
    return list(TAXONOMY)


def speech_names(keys: list[str], limit: int = 4) -> str:
    """Человеческие названия групп для произнесения вслух.

    Перечисляем не всё: девять названий голосом — это двадцать секунд
    и ни одного запоминаемого. Лучше назвать самые ходовые и сказать,
    что остальное — на панели.
    """
    parts = [TAXONOMY[k].short for k in keys if k in TAXONOMY][:limit]
    return ", ".join(parts)