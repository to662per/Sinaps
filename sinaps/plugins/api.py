"""Витрина публичного API. Единственная точка входа для плагинов.

Что это за витрина и зачем
-------------------------
Плагин не должен знать, как устроено ядро. Он должен знать, что есть
несколько типов, которые можно создать, и функция, куда их записать.
Всё остальное — внутреннее устройство, которое можно менять как
угодно.

Пока этого файла не было, любой плагин писал `from sinaps.skills.base
import Skill` — то есть зависел от внутренностей. Стоит перенести класс
или переименовать модуль — и все плагины ломались. Объявлять совместимость
приходилось со всем подряд, а это как раз то, чего проект избегает.

Теперь контракт лежит в одном месте и читается целиком. Плагин импортирует
`sinaps.plugins.api` — и больше ничего из пакета.

Что обещает этот модуль
-----------------------
Всё, что перечислено в `__all__`, не меняется без мажорной версии.
Всё, чего там нет, — внутреннее, и может измениться когда угодно.

Именно поэтому список короткий. Намётанный навык обнаруживает, что
внутренности полезны для расширения, и начинает их использовать — а
потом внутренности меняются, и он ломается.

Правила для плагина
-------------------
1. Импортировать **только** отсюда. Прямые `from sinaps... import ...`
   запрещены и проверяются тестом: плагин поймает несовместимость при
   первой же загрузке, а не через полгода.
2. Не сохранять ссылки на переданные объекты. Реестр может быть
   пересобран; брать его на каждый вызов.
3. Ошибки — из этого же модуля. Свои исключения ядро не увидит, и
   плагин будет падать молча.

Чего здесь нет и почему
------------------------
* **`PlatformCapabilities` напрямую.** Плагин получает прокси, который
  проверяет разрешения. Настоящий объект отдавать нельзя: иначе любой
  плагин сможет выключить компьютер, объявив одно разрешение или
  ничего не объявив.
* **`MemoryStore`.** Плагину достаётся `ctx.state` — своё именованное
  пространство с проверкой прав. Прямой доступ к базе означал бы, что
  один плагин видит состояние другого.
* **`runtime`, `engine`, `bus`.** Это устройство конвейера, а не
  контракт с плагином. Плагину они нужны, чтобы зарегистрироваться,
  а не чтобы пересобрать ассистента.
* **Движки речи (`stt`, `tts`, `vad`).** Приватность проекта
  строится на том, что звук не покидает машину. Если дать плагину
  доступ к синтезу, ничто не помешает ему отправить текст в облако.

Что приходит в обработчик
-------------------------
`DialogContext` с теми же полями, что и в ядре, плюс `ctx.state`.

Плагин исполняется в дочернем процессе, поэтому `platform` и `session`
через границу не переносятся: `platform` — это владение компьютером, а
`session` не переживает сериализацию. Настоящий объект платформы
плагину не достаётся никогда.

`ctx.state` — своё именованное пространство плагина. Методы
асинхронные, потому что хранилище лежит в ядре, а плагин — в другом
процессе:

    n = await ctx.state.get("счётчик", 0)
    await ctx.state.set("счётчик", n + 1)
    всё = await ctx.state.all()

Без одобрения права `state` любой вызов бросает `PermissionDenied`.
"""

