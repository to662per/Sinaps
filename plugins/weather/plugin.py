#: Имена городов в именительном падеже — для подсказки в ответе.
CITY_NAMES = tuple(CITIES_DEF)


def _build_index() -> dict[str, tuple[float, float, str]]:
    """Собрать индекс «любая форма → (координаты, каноническое имя)».

    Каноническое имя нужно для ответа: из слота приходит падеж
    («питере»), а произносить и показывать надо именительный — иначе
    ассистент скажет «Питере: 3°C».

    Первый город с формой выигрывает: иначе слово, которое значит два
    города, досталось бы молча последнему в списке.

    Рядом добавляется вариант с `ё`→`е`: нормализация входного текста в
    ядре заменяет «ё» на «е», и без этого «Могилёве» превратился бы в
    «Могилеве», которого в таблице нет, и город просто не нашёлся бы.
    """
    index: dict[str, tuple[float, float, str]] = {}

    def put(variant: str, coords: tuple[float, float, str]) -> None:
        key = variant.strip().lower()
        if not key:
            return
        if key not in index:
            index[key] = coords
        swapped = key.replace("ё", "е")
        if "ё" in key and swapped not in index:
            index[swapped] = coords

    for name, data in CITIES_DEF.items():
        coords = (data["lat"], data["lon"], name)
        put(name, coords)
        for form in data["forms"]:
            put(form.removeprefix("о ").removeprefix("об "), coords)
        for alias, forms in data["alias"].items():
            put(alias, coords)
            for form in forms:
                put(form, coords)
    return index


#: Индекс для поиска: любая форма города → координаты и имя.
CITIES = _build_index()


def _lookup_city(raw: str) -> tuple[float, float, str] | None:
    """Найти город по любой форме.

    Ведущее «о», «об» и «во» отбрасывается: без этого «о Гомеле» не
    совпало бы с «Гомелем», хотя по-русски это один и тот же город.
    """
    key = (raw or "").strip().lower()
    for prefix in ("о ", "об ", "во "):
        if key.startswith(prefix):
            key = key[len(prefix):]
            break
    found = CITIES.get(key)
    if found is None and "ё" in key:
        found = CITIES.get(key.replace("ё", "е"))
    return found


async def _fetch_weather(lat: float, lon: float, days: int = 3) -> dict[str, Any]:
    """Запрос к Open-Meteo.

    Импорт urllib внутри функции — чтобы песочница не блокировала
    загрузку модуля плагина на этапе импорта.
    """
    import urllib.request

    base = "https://api.open-meteo.com/v1/forecast"
    params = (
        f"latitude={lat}&longitude={lon}"
        f"&current_weather=true"
        f"&daily=temperature_2m_max,temperature_2m_min,weathercode"
        f"&timezone=auto"
        f"&forecast_days={days}"
    )
    url = f"{base}?{params}"

    def do_request():
        req = urllib.request.Request(url, headers={"User-Agent": "Sinaps/1.0"})
        with urllib.request.urlopen(req, timeout=10) as resp:
            return json.loads(resp.read().decode("utf-8"))

    return await asyncio.to_thread(do_request)


